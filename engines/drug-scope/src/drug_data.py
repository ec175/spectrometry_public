"""drug_data.py — molecule + spectrum data for the CRT-scope "drug profile" format.

Transcribed 1:1 from the manim VerticalProfile_* subclasses in
the project's manim spectroscopy scenes (AT / BONDS / LBL_ATOM / ir_lines /
titles / vib_modes). Colours (per-symbol trace hue, bond green) live in `osc.drugscope.ROLE`.

Coordinate convention matches the manim builders: build-space (x right, y UP); BB = fixed
bounding box for a stable scale. An AT value may be (x, y) OR (x, y, z) — a z coord makes the
structure genuinely 3D and the billboard rock reveals its depth (Morphine).
LBL entries are (atom, text, role); role keys the trace colour (see ROLE): O, N, S, Cl, dim, C.

FTIR band legend = the molecule's `vib_modes` (name, band). The Raman spectrum shares the same
band POSITIONS (IR and Raman probe the same vibrational modes) but has a genuinely DIFFERENT
intensity profile, because the two obey different selection rules:
  - IR intensity  ∝ change in dipole moment  -> POLAR modes strong (C=O, C-O, N-H, S=O).
  - Raman intensity ∝ change in polarizability -> SYMMETRIC / nonpolar modes strong
    (C=C, aromatic ring, ring breathing, C-C skeletal, C-S).
`_raman_from_ir` applies that wavenumber-keyed reweight (illustrative, not measured), so the
Raman trace clearly differs from FTIR — the dominant IR C=O/C-O peaks shrink while the
aromatic/skeletal bands rise. The Raman legend is the same diagnostic modes REORDERED by their
Raman strength, so its numbered markers land on different peaks than the FTIR legend's.
"""
from __future__ import annotations


def _raman_factor(cm):
    """Illustrative Raman/IR intensity ratio by band region (see module docstring)."""
    if cm >= 1660:
        return 0.30        # C=O and above: IR-strong, Raman-weak
    if cm >= 1560:
        return 1.90        # C=C aromatic: Raman-strong
    if cm >= 1440:
        return 1.25        # aromatic ring / CH2 scissor
    if cm >= 1330:
        return 0.85
    if cm >= 1180:
        return 0.50        # C-O / amide III / C-N: IR-strong, Raman-weak
    if cm >= 980:
        return 1.85        # C-C skeletal / ring breathing: Raman-strong
    if cm >= 780:
        return 1.20
    return 1.55            # ring / C-S / C-Cl / skeletal bend: Raman-strong


def _raman_from_ir(ir_lines):
    """Reweight an IR line list into an illustrative Raman fingerprint (same positions)."""
    return [(cm, round(inten * _raman_factor(cm), 3)) for cm, inten in ir_lines]


def _raman_bands(vib_bands, ir_lines):
    """Same diagnostic modes as FTIR, REORDERED by Raman intensity (so the numbered markers land
    on different peaks). Raman intensity of a band = its IR intensity x the Raman/IR factor."""
    ir = dict(ir_lines)

    def _ri(cm):
        inten = ir.get(cm) or min(ir_lines, key=lambda t: abs(t[0] - cm))[1]
        return inten * _raman_factor(cm)
    return sorted(vib_bands, key=lambda nb: -_ri(nb[1]))


