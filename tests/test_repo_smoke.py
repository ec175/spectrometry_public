"""Fast, dependency-light repository checks used by local development and CI."""
import json
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


class RepositorySmokeTests(unittest.TestCase):
    def test_each_engine_has_readme_and_valid_catalogue(self):
        for path in (ROOT / "engines").glob("*/catalog.json"):
            with self.subTest(engine=path.parent.name):
                self.assertTrue((path.parent / "README.md").is_file())
                data = json.loads(path.read_text(encoding="utf-8"))
                self.assertIsInstance(data, dict)
                self.assertTrue(data.get("title"))

    def test_catalogue_outputs_are_marked_generated(self):
        for path in (ROOT / "engines").glob("*/CATALOG.md"):
            with self.subTest(catalogue=path.parent.name):
                self.assertIn("Generated by tools/build_catalogs.py", path.read_text(encoding="utf-8")[:300])

    def test_removed_coming_soon_items_are_absent_from_public_galleries(self):
        for path in (ROOT / "README.md", ROOT / "docs/index.html"):
            text = path.read_text(encoding="utf-8").lower()
            for slug in ("mechanics-board", "cinematic.webp", "elements.webp", "field-notes.webp", "cow-launch"):
                with self.subTest(file=path.name, item=slug):
                    self.assertNotIn(slug, text)


if __name__ == "__main__":
    unittest.main()
